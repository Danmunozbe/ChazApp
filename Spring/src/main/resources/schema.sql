DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS chazas;

CREATE TABLE chazas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    ubicacion VARCHAR(200),
    imagen_url VARCHAR(255),
    menu_publicado BOOLEAN NOT NULL DEFAULT TRUE,
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chaza_id BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    categoria VARCHAR(100),
    precio DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    imagen_url VARCHAR(255),
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_producto_chaza FOREIGN KEY (chaza_id) REFERENCES chazas(id) ON DELETE CASCADE
);
